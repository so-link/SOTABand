"""Capabilities a workflow may request from its conversation host."""

from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Any, Protocol


class WorkflowHost(Protocol):
    llm: Any

    def resolve_dataset_paths(self, attachments: list) -> list[str]: ...

    async def execute_tool(self, tool: dict, query: str, paths=None, params=None) -> dict: ...

    async def check_missing_params(self, tool_id: str, params: dict, mode=None) -> list: ...

    def get_tool_modes(self, tool_id: str) -> list: ...

    def resolve_mode_selection(self, answer: str, modes: list) -> dict | None: ...

    def resolve_tool_selection(self, answer: str, candidates: list) -> dict | None: ...

    def get_path_params(self, tool_id: str, mode=None) -> list: ...

    async def extract_params(self, query: str, tool_id: str, paths=None) -> dict: ...

    def submit_task_result(self, result: dict, tool: dict) -> dict: ...

    def respond(self, ctx, content, attachments, workspace_tool_ids=None,
                tool_result=None) -> AsyncIterator[dict]: ...
